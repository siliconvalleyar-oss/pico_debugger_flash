static void ssd1306_write_cmd(ssd1306_t *disp, uint8_t cmd) {
    uint8_t buf[2] = {0x00, cmd};
    i2c_write_blocking(disp->i2c, disp->address, buf, 2, false);
}

static void ssd1306_write_cmds(ssd1306_t *disp, const uint8_t *cmds, size_t len) {
    uint8_t buf[len + 1];
    buf[0] = 0x00;
    memcpy(buf + 1, cmds, len);
    i2c_write_blocking(disp->i2c, disp->address, buf, len + 1, false);
}

static void ssd1306_write_data(ssd1306_t *disp, const uint8_t *data, size_t len) {
    uint8_t buf[len + 1];
    buf[0] = 0x40;
    memcpy(buf + 1, data, len);
    i2c_write_blocking(disp->i2c, disp->address, buf, len + 1, false);
}

bool ssd1306_init(ssd1306_t *disp, i2c_inst_t *i2c, uint8_t address, uint8_t width, uint8_t height) {
    disp->i2c = i2c;
    disp->address = address;
    disp->width = width;
    disp->height = height;
    disp->inverted = false;
    memset(disp->buffer, 0, sizeof(disp->buffer));

    const uint8_t cmds[] = {
        0xAE,           // Display off
        0xD5, 0x80,     // Set display clock divide ratio/oscillator frequency
        0xA8, 0x3F,     // Set multiplex ratio (1 to 64)
        0xD3, 0x00,     // Set display offset
        0x40,           // Set start line address
        0x8D, 0x14,     // Charge pump setting
        0x20, 0x00,     // Set memory addressing mode (horizontal)
        0xA1,           // Set segment re-map (column 127 mapped to SEG0)
        0xC8,           // Set COM output scan direction (COM63 to COM0)
        0xDA, 0x12,     // Set COM pins hardware configuration
        0x81, 0xCF,     // Set contrast control
        0xD9, 0xF1,     // Set pre-charge period
        0xDB, 0x40,     // Set VCOMH deselect level
        0xA4,           // Entire display on (resume)
        0xA6,           // Normal display (not inverted)
        0xAF            // Display on
    };
    ssd1306_write_cmds(disp, cmds, sizeof(cmds));
    sleep_ms(100);
    ssd1306_clear(disp);
    ssd1306_show(disp);
    return true;
}

void ssd1306_deinit(ssd1306_t *disp) {
    ssd1306_write_cmd(disp, 0xAE); // Display off
}

void ssd1306_clear(ssd1306_t *disp) {
    memset(disp->buffer, 0, sizeof(disp->buffer));
}

void ssd1306_show(ssd1306_t *disp) {
    const uint8_t cmds[] = {
        0x21, 0, disp->width - 1,   // Column address
        0x22, 0, SSD1306_PAGES - 1  // Page address
    };
    ssd1306_write_cmds(disp, cmds, sizeof(cmds));
    ssd1306_write_data(disp, disp->buffer, disp->width * SSD1306_PAGES);
}

void ssd1306_set_pixel(ssd1306_t *disp, int x, int y, bool on) {
    if (x < 0 || x >= disp->width || y < 0 || y >= disp->height) return;
    int page = y / 8;
    int bit = y % 8;
    int idx = x + page * disp->width;
    if (on) disp->buffer[idx] |= (1 << bit);
    else disp->buffer[idx] &= ~(1 << bit);
}

void ssd1306_draw_char(ssd1306_t *disp, int x, int y, char c, bool inverted) {
    if (c < 32 || c > 126) return;
    const uint8_t *glyph = font5x8[c - 32];
    for (int i = 0; i < 5; i++) {
        uint8_t line = glyph[i];
        if (inverted) line = ~line;
        for (int j = 0; j < 8; j++) {
            ssd1306_set_pixel(disp, x + i, y + j, line & (1 << j));
        }
    }
    // Space after char
    for (int j = 0; j < 8; j++) {
        ssd1306_set_pixel(disp, x + 5, y + j, inverted);
    }
}

void ssd1306_draw_string(ssd1306_t *disp, int x, int y, const char *str, bool inverted) {
    while (*str) {
        ssd1306_draw_char(disp, x, y, *str++, inverted);
        x += 6;
        if (x > disp->width - 6) break;
    }
}

void ssd1306_draw_line(ssd1306_t *disp, int x1, int y1, int x2, int y2, bool color) {
    int dx = abs(x2 - x1), sx = x1 < x2 ? 1 : -1;
    int dy = -abs(y2 - y1), sy = y1 < y2 ? 1 : -1;
    int err = dx + dy, e2;
    while (true) {
        ssd1306_set_pixel(disp, x1, y1, color);
        if (x1 == x2 && y1 == y2) break;
        e2 = 2 * err;
        if (e2 >= dy) { err += dy; x1 += sx; }
        if (e2 <= dx) { err += dx; y1 += sy; }
    }
}

void ssd1306_draw_rect(ssd1306_t *disp, int x, int y, int w, int h, bool filled, bool color) {
    if (filled) {
        for (int i = 0; i < w; i++)
            for (int j = 0; j < h; j++)
                ssd1306_set_pixel(disp, x + i, y + j, color);
    } else {
        ssd1306_draw_line(disp, x, y, x + w - 1, y, color);
        ssd1306_draw_line(disp, x, y + h - 1, x + w - 1, y + h - 1, color);
        ssd1306_draw_line(disp, x, y, x, y + h - 1, color);
        ssd1306_draw_line(disp, x + w - 1, y, x + w - 1, y + h - 1, color);
    }
}

void ssd1306_invert_display(ssd1306_t *disp, bool invert) {
    disp->inverted = invert;
    ssd1306_write_cmd(disp, invert ? 0xA7 : 0xA6);
}

void ssd1306_set_contrast(ssd1306_t *disp, uint8_t contrast) {
    uint8_t cmds[] = {0x81, contrast};
    ssd1306_write_cmds(disp, cmds, 2);
}

void ssd1306_draw_graph(ssd1306_t *disp, int x, int y, int w, int h, const float *values, int count, float min_val, float max_val, const char *title) {
    if (count < 2) return;
    
    if (title) {
        ssd1306_draw_string(disp, x, y - 10, title, false);
    }
    
    // Draw axes
    ssd1306_draw_line(disp, x, y + h, x + w, y + h, true); // X axis
    ssd1306_draw_line(disp, x, y, x, y + h, true); // Y axis
    
    float range = max_val - min_val;
    if (range == 0) range = 1;
    
    for (int i = 1; i < count; i++) {
        int x1 = x + (i - 1) * w / (count - 1);
        int x2 = x + i * w / (count - 1);
        int y1 = y + h - (int)((values[i - 1] - min_val) / range * h);
        int y2 = y + h - (int)((values[i] - min_val) / range * h);
        ssd1306_draw_line(disp, x1, y1, x2, y2, true);
    }
}