static void oled_cmd(uint8_t c) {
    uint8_t buf[2] = {0x00, c};
    i2c_write_blocking(OLED_I2C, OLED_ADDR, buf, 2, false);
}

static void oled_data(uint8_t *p, size_t n) {
    if (!n) return;
    uint8_t data[130];
    data[0] = 0x40;
    memcpy(data + 1, p, n);
    i2c_write_blocking(OLED_I2C, OLED_ADDR, data, n + 1, false);
}

void ssd1306_init(void) {
    i2c_init(OLED_I2C, OLED_I2C_FREQ);
    gpio_set_function(OLED_SDA_PIN, GPIO_FUNC_I2C);
    gpio_set_function(OLED_SCL_PIN, GPIO_FUNC_I2C);
    gpio_pull_up(OLED_SDA_PIN);
    gpio_pull_up(OLED_SCL_PIN);

    oled_cmd(0xAE); /* display off */
    oled_cmd(0xD5); oled_cmd(0x80); /* clock div */
    oled_cmd(0xA8); oled_cmd(0x3F); /* multiplex 1/64 */
    oled_cmd(0xD3); oled_cmd(0x00); /* display offset */
    oled_cmd(0x40); /* start line 0 */
    oled_cmd(0x8D); oled_cmd(0x14); /* charge pump on */
    oled_cmd(0x20); oled_cmd(0x00); /* horizontal addressing */
    oled_cmd(0xA1); /* segment remap */
    oled_cmd(0xC8); /* COM scan direction */
    oled_cmd(0xDA); oled_cmd(0x12); /* COM pins */
    oled_cmd(0x81); oled_cmd(0xCF); /* contrast */
    oled_cmd(0xD9); oled_cmd(0xF1); /* pre-charge */
    oled_cmd(0xDB); oled_cmd(0x40); /* vcom detect */
    oled_cmd(0xA4); /* display on, no resume */
    oled_cmd(0xA6); /* normal display */
    oled_cmd(0x2E); /* deactivate scroll */

    ssd1306_clear();
    ssd1306_flush();
    oled_cmd(0xAF); /* display on */
}

void ssd1306_clear(void) { memset(fb, 0, sizeof(fb)); }

void ssd1306_flush(void) {
    for (int page = 0; page < 8; page++) {
        oled_cmd(0xB0 + page);
        oled_cmd(0x00); /* col low */
        oled_cmd(0x10); /* col high = 0 */
        oled_data(fb + page * 128, 128);
    }
}

void ssd1306_putc(uint8_t x, uint8_t y, char c) {
    if (y > 7 || x > 123) return;
    if (c < 32 || c > 95) return;
    const uint8_t *g = font5x7[c - 32];
    for (int i = 0; i < 5; i++) {
        uint8_t col = g[i];
        fb[y * 128 + x + i] = col;
    }
    fb[y * 128 + x + 5] = 0;
}

void ssd1306_puts(uint8_t x, uint8_t y, const char *s) {
    while (*s) {
        ssd1306_putc(x, y, *s);
        x += 6;
        s++;
    }
}

void ssd1306_fill_rect(uint8_t x, uint8_t y, uint8_t w, uint8_t h, bool on) {
    for (uint8_t yy = y; yy < y + h; yy++) {
        if (yy >= 64) break;
        for (uint8_t xx = x; xx < x + w; xx++) {
            if (xx >= 128) break;
            uint8_t bit = 1 << (yy % 8);
            uint8_t &pix = fb[(yy / 8) * 128 + xx];
            if (on) pix |= bit;
            else pix &= (uint8_t)~bit;
        }
    }
}

void ssd1306_bar(uint8_t x, uint8_t y, uint8_t w, uint8_t h, uint8_t pct) {
    ssd1306_fill_rect(x, y, w, h, false);
    uint8_t fill = (uint8_t)((w * pct) / 100u);
    ssd1306_fill_rect(x, y, fill, h, true);
}